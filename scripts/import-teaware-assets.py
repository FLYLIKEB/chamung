"""Copy Deep Colony tools and derive palette variants without changing geometry.
Usage: python3 scripts/import-teaware-assets.py /path/to/deep-colony
Source files are read only. Variant IDs and filenames are stable.
"""
import hashlib
import json
import shutil
import sys
from pathlib import Path
from PIL import Image

source = Path(sys.argv[1])
root = Path(__file__).resolve().parents[1]
out = root / 'public/teaware/presets'
out.mkdir(parents=True, exist_ok=True)
manifest = json.loads((source / 'output/imagegen/teaware-30/manifest.json').read_text())
kind_by_slug = {
 'gaiwan':'gaiwan','purple-pot':'yixing','red-clay-pot':'yixing',
 'stoneware-pot':'teapot','celadon-pot':'teapot','iron-kettle':'kettle','copper-kettle':'kettle',
 'fairness-cup':'pitcher','water-pitcher':'pitcher','tea-strainer':'strainer',
 'wood-tray':'tray','bamboo-tray':'tray',
}
styles = [
 ('ivory','백유빛',['635b48','969879','c4c7a8','e3e4ca','f5f1d9']),
 ('jade','청자빛',['3b5149','5d7b64','81a486','b0c6a3','d9e4c9']),
 ('blue','청화빛',['304353','496b87','7898ad','b6c8cb','edf0dd']),
 ('charcoal','흑유빛',['292c2b','454846','656d65','959b87','c5cbb4']),
 ('ochre','황유빛',['64472c','98713d','bd9553','d9b975','ebd69e']),
 ('speckle','점무늬',['565a4d','858775','afb49a','d1d5bc','eeecd6']),
 ('brown','갈유빛',['513d31','76533c','a4714d','c39870','e2c6a0']),
]
clay_labels=['연갈빛','회갈빛','청회빛','흑니빛','단니빛','점무늬','주니빛']
wood_labels=['밝은 나무빛','대나무빛','청회빛','흑칠빛','황갈빛','점무늬','옻갈빛']
metal_labels=['은빛','청동빛','강철빛','흑철빛','황동빛','점무늬','동빛']
records=[]; provenance=[]
entries=[]
for item in manifest:
 slug=item['slug']; kind='cup' if item['group']=='cup' else kind_by_slug.get(slug,'accessory')
 entries.append((slug,item['name'],kind,'dist/'+item['image']))
entries += [('crew-pot','백유 다관','teapot','dist/assets/characters/crew/tools/pot.png'),('crew-cup','백유 찻잔','cup','dist/assets/characters/crew/tools/cup.png'),('crew-kettle','동제 탕관','kettle','dist/assets/characters/crew/tools/kettle.png')]
for slug,name,kind,relative in entries:
 original=source/relative
 image=Image.open(original).convert('RGBA')
 pixels=list(image.getdata());w,h=image.size
 for variant_index,style in enumerate([None]+styles):
  style_id,label,palette=style if style else ('original','원본',[])
  variant_id=f'dc-{slug}-{style_id}'
  filename=variant_id+'.png'
  if not style: shutil.copyfile(original,out/filename)
  else:
   colors=[tuple(bytes.fromhex(c)) for c in palette]
   result=image.copy();target=result.load()
   for y in range(h):
    for x in range(w):
     r,g,b,a=pixels[y*w+x]
     light=.2126*r+.7152*g+.0722*b
     # Preserve transparent pixels and the original dark outline exactly.
     if a==0 or light<55: continue
     t=max(0,min(4,(light-45)/195*4));lo=int(t);hi=min(4,lo+1);part=t-lo
     color=tuple(round(colors[lo][i]*(1-part)+colors[hi][i]*part) for i in range(3))
     # Small glaze marks stay strictly inside the original opaque silhouette.
     interior=0<x<w-1 and 0<y<h-1 and all(pixels[ny*w+nx][3]>0 for nx,ny in [(x-1,y),(x+1,y),(x,y-1),(x,y+1)])
     if interior and light>100 and style_id=='speckle' and (x*3+y*5)%17==0: color=colors[1]
     if interior and light>100 and style_id=='blue' and y in [round(h*.42),round(h*.68)]: color=colors[1]
     target[x,y]=(*color,a)
   assert result.getchannel('A').tobytes()==image.getchannel('A').tobytes()
   result.save(out/filename,optimize=True)
  label=(clay_labels if kind=='yixing' else metal_labels if kind in ['kettle','strainer'] else wood_labels if kind in ['accessory','tray'] else [s[1] for s in styles])[variant_index-1] if style else ''
  records.append({'variantId':variant_id,'kind':kind,'name':name+(f' · {label}' if label else ''),'imagePath':'/teaware/presets/'+filename})
 provenance.append({'source':relative,'baseId':slug,'sha256':hashlib.sha256(original.read_bytes()).hexdigest(),'size':list(image.size)})
shutil.copyfile(source/'dist/assets/world/buildings/base/DecorTileBambooWeave.png',root/'public/teaware/bamboo-weave.png')
registry=root/'backend/src/teaware/teaware-presets.ts'
registry.write_text('// Generated by scripts/import-teaware-assets.py. Keep IDs stable for saved notes.\nexport const TEAWARE_VARIANTS = '+json.dumps(records,ensure_ascii=False,indent=2)+' as const;\n')
(root/'public/teaware/source-manifest.json').write_text(json.dumps({'sourceProject':'deep-colony','generator':'scripts/import-teaware-assets.py','sources':provenance},ensure_ascii=False,indent=2)+'\n')
print('Imported',len(entries),'originals;',len(records),'choices')
print({kind:sum(r['kind']==kind for r in records) for kind in sorted({r['kind'] for r in records})})
